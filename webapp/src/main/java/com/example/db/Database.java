package com.example.db;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Hands out database connections and creates the schema on first use.
 *
 * Configuration comes from environment variables (set from a Kubernetes Secret):
 *   DB_URL       e.g. jdbc:postgresql://host:5432/registerapp?sslmode=require
 *   DB_USER
 *   DB_PASSWORD
 *
 * If DB_URL is not set, the app still serves its static pages; database-backed
 * pages show a friendly "not connected" message instead of crashing.
 */
public final class Database {

    private static final String SCHEMA =
        "CREATE TABLE IF NOT EXISTS users ("
      + "  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
      + "  full_name     VARCHAR(100) NOT NULL,"
      + "  mobile        VARCHAR(20)  NOT NULL,"
      + "  email         VARCHAR(254) NOT NULL UNIQUE,"
      + "  password_hash VARCHAR(255) NOT NULL,"
      + "  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()"
      + ")";

    private static volatile boolean schemaReady = false;

    private Database() { }

    public static boolean isConfigured() {
        String url = System.getenv("DB_URL");
        return url != null && !url.trim().isEmpty();
    }

    /** Opens a new connection. Callers must close it (try-with-resources). */
    public static Connection getConnection() throws SQLException {
        if (!isConfigured()) {
            throw new SQLException("Database is not configured (DB_URL is not set).");
        }
        try {
            Class.forName("org.postgresql.Driver");
        } catch (ClassNotFoundException e) {
            throw new SQLException("PostgreSQL driver is missing from the application.", e);
        }
        Connection connection = DriverManager.getConnection(
            System.getenv("DB_URL"), System.getenv("DB_USER"), System.getenv("DB_PASSWORD"));
        ensureSchema(connection);
        return connection;
    }

    private static void ensureSchema(Connection connection) throws SQLException {
        if (schemaReady) {
            return;
        }
        synchronized (Database.class) {
            if (!schemaReady) {
                try (Statement statement = connection.createStatement()) {
                    statement.execute(SCHEMA);
                }
                schemaReady = true;
            }
        }
    }
}
